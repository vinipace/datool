import { readFile, writeFile, lstat } from "node:fs/promises"
import { resolve } from "node:path"
import { build, type BuildOptions } from "esbuild"
import ts from "typescript"
import { gzipSync } from "node:zlib"

const generated = `// Generated by datool deploy. Do not edit.\nimport * as schema from "./schema"\nimport { drizzle } from "drizzle-orm/pg-proxy"\nimport { createProject } from "@datool/sdk/deploy"\nexport const { defineTool, defineSource } = createProject((ctx) =>\n  drizzle((query, params, method) => ctx.query(query, params, method), { schema })\n)\nexport type ProjectContext = Parameters<Parameters<typeof defineSource>[0]>[0]\n`
let compiler: Promise<string> | undefined
function schemaCompiler() {
  compiler ??= build({
    stdin: {
      contents:
        'const {generateDrizzleJson} = require("drizzle-kit/api"); module.exports = generateDrizzleJson;',
      resolveDir: import.meta.dirname,
    },
    bundle: true,
    write: false,
    minify: true,
    platform: "node",
    format: "cjs",
    define: {
      "import.meta.url": JSON.stringify(
        "file:///workspace/schema-compiler.cjs"
      ),
    },
    external: [
      "esbuild",
      "@libsql/client",
      "pg",
      "pg-native",
      "@electric-sql/pglite",
      "postgres",
      "@vercel/postgres",
      "@neondatabase/serverless",
      "mysql2",
      "mysql2/*",
      "@planetscale/database",
      "better-sqlite3",
      "@aws-sdk/client-rds-data",
    ],
  }).then((result) => gzipSync(result.outputFiles[0].text).toString("base64"))
  return compiler
}

/** Compile declarations without importing schema.ts into the credential-bearing CLI. */
export async function prepareDatabase(
  root: string,
  entries: string[],
  options: BuildOptions
) {
  const path = resolve(root, "schema.ts")
  const info = await lstat(path).catch((error) => {
    if (error.code === "ENOENT") return null
    throw error
  })
  if (!info) return undefined
  if (!info.isFile() || info.isSymbolicLink())
    throw new Error("schema.ts must be a regular file.")
  const generatedPath = resolve(root, "datool.generated.ts")
  const old = await readFile(generatedPath, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null
    throw error
  })
  if (
    old !== null &&
    !old.startsWith("// Generated by datool deploy. Do not edit.\n")
  )
    throw new Error(
      "datool.generated.ts already exists and is not managed by Datool."
    )
  if ((await lstat(generatedPath).catch(() => null))?.isSymbolicLink())
    throw new Error("datool.generated.ts cannot be a symlink.")
  await writeFile(generatedPath, generated)
  const program = ts.createProgram(
    [path, generatedPath, ...entries.map((entry) => resolve(root, entry))],
    {
      noEmit: true,
      strict: true,
      skipLibCheck: true,
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      allowImportingTsExtensions: true,
      esModuleInterop: true,
      allowJs: true,
      checkJs: true,
      typeRoots: [resolve(root, "node_modules/@types")],
    }
  )
  const errors = ts.getPreEmitDiagnostics(program)
  if (errors.length)
    throw new Error(
      ts.formatDiagnosticsWithColorAndContext(errors, {
        getCanonicalFileName: (name) => name,
        getCurrentDirectory: () => root,
        getNewLine: () => "\n",
      })
    )
  const schema = await build({
    ...options,
    stdin: {
      contents: 'export * from "./schema.ts"',
      resolveDir: root,
      sourcefile: "datool-schema.ts",
    },
  })
  const code = `import {createRequire} from 'node:module';const require=createRequire('/workspace/schema.cjs');import {gunzipSync} from 'node:zlib';\nconst generate=(()=>{const module={exports:{}};new Function('require','module','exports','__filename','__dirname',gunzipSync(Buffer.from('${await schemaCompiler()}','base64')).toString())(require,module,module.exports,'/workspace/compiler.cjs','/workspace');return module.exports;})();\nconst schema=await import('data:text/javascript;base64,${Buffer.from(schema.outputFiles![0].text).toString("base64")}');\nexport const describeDatabase=()=>generate(schema);`
  if (Buffer.byteLength(code) > 2 * 1024 * 1024)
    throw new Error("Bundled PostgreSQL schema exceeds 2 MiB.")
  return { code }
}
